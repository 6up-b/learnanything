@dataclass(frozen=True)
class Site:
    table: str
    kind: str  # write | read | named
    path: str  # relative to src/
    line: int
    unit: str  # the innermost function (qualname), or the module constant holding the string, or "<module>"
    reached: bool
    guarded: bool
    category: str

    @property
    def where(self) -> str:
        path = self.path[len("learnloop/"):] if self.path.startswith("learnloop/") else self.path
        return f"{path}:{self.line}"


@dataclass
class _RawSite:
    table: str
    kind: str
    path: str
    line: int
    unit: str
    reach_name: str | None
    guarded: bool


def _category(path: str) -> str:
    if path in LIST_FILES:
        return LIST_FILES[path]
    for step, files in IN_FLIGHT.items():
        if path in files:
            return step
    stem = Path(path).stem
    if stem.endswith("_upgrade") or path.endswith("recurrence/upgrade.py") or path == "learnloop/ops/vault_upgrade.py":
        return "upgrade"
    if path in REBUILD_FILES:
        return "rebuild"
    if "sync" in path:
        return "sync"
    return "code"


def _docstring_nodes(tree: ast.AST) -> set[int]:
    ids: set[int] = set()
    for node in ast.walk(tree):
        if isinstance(node, (ast.Module, ast.ClassDef, ast.FunctionDef, ast.AsyncFunctionDef)):
            body = node.body
            if body and isinstance(body[0], ast.Expr) and isinstance(body[0].value, ast.Constant) and isinstance(body[0].value.value, str):
                ids.add(id(body[0].value))
    return ids


def _module_constants(tree: ast.Module) -> dict[str, str]:
    constants: dict[str, str] = {}
    for node in tree.body:
        if isinstance(node, ast.Assign) and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            target, value = node.targets[0].id, node.value
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name) and node.value is not None:
            target, value = node.target.id, node.value
        else:
            continue
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            constants[target] = value.value
    return constants


def _fstring_text(node: ast.JoinedStr, constants: Mapping[str, str]) -> str:
    parts: list[str] = []
    for value in node.values:
        if isinstance(value, ast.Constant) and isinstance(value.value, str):
            parts.append(value.value)
        elif isinstance(value, ast.FormattedValue):
            inner = value.value
            name = inner.id if isinstance(inner, ast.Name) else (inner.attr if isinstance(inner, ast.Attribute) else None)
            parts.append(constants.get(name, " {?} ") if name else " {?} ")
    return "".join(parts)


def _classify_text(text: str, tables: frozenset[str]) -> list[tuple[str, str]]:
    """``(table, kind)`` pairs a string holds: writes and reads when it is SQL, else a bare table name."""

    if SQL_KEYWORD.search(text):
        found: list[tuple[str, str]] = []
        writes = {m.group(1) for m in WRITE_SQL.finditer(text)} & tables
        found.extend((table, "write") for table in sorted(writes))
        stripped = WRITE_SQL.sub(" ", text)
        reads = {m.group(1) or m.group(2) for m in READ_SQL.finditer(stripped)} & tables
        found.extend((table, "read") for table in sorted(reads))
        return found
    bare = text.strip().strip('"`')
    return [(bare, "named")] if bare in tables else []


class _FileScanner(ast.NodeVisitor):
    def __init__(
        self, path: str, source: str, tree: ast.Module, tables: frozenset[str], prepass: _Prepass,
    ):
        self.path = path
        self.lines = source.splitlines()
        self.tables = tables
        self.constants = {**prepass.constants, **_module_constants(tree)}
        self.dynamic = prepass.dynamic
        self.handled: set[int] = set()
        self.docstrings = _docstring_nodes(tree)
        self.stack: list[tuple[str, bool]] = []  # (function name, its own text has a guard)
        self.classes: list[str] = []
        self.assign_target: str | None = None
        self.sites: list[_RawSite] = []
        #: function name -> identifiers its body mentions; module- and class-level mentions are seeds.
        self.defs: list[tuple[str, set[str]]] = []
        self.seeds: set[str] = set()
        self._refs: list[set[str]] = []

    # names
    def _mention(self, name: str) -> None:
        (self._refs[-1] if self._refs else self.seeds).add(name)

    def visit_Name(self, node: ast.Name) -> None:
        self._mention(node.id)

    def visit_Attribute(self, node: ast.Attribute) -> None:
        self._mention(node.attr)
        self.generic_visit(node)

    def _visit_function(self, node: ast.FunctionDef | ast.AsyncFunctionDef) -> None:
        for decorator in node.decorator_list:
            self.visit(decorator)
        if node.decorator_list or (node.name.startswith("__") and node.name.endswith("__")):
            self.seeds.add(node.name)
        for default in [*node.args.defaults, *node.args.kw_defaults]:
            if default is not None:
                self.visit(default)
        segment = "\n".join(self.lines[node.lineno - 1 : node.end_lineno or node.lineno])
        self.stack.append((node.name, bool(GUARD.search(segment))))
        refs: set[str] = set()
        self._refs.append(refs)
        for statement in node.body:
            self.visit(statement)
        self._refs.pop()
        self.stack.pop()
        self.defs.append((node.name, refs))
        if self._refs:  # a nested function is reached through its enclosing one
            self._refs[-1].add(node.name)

    visit_FunctionDef = _visit_function
    visit_AsyncFunctionDef = _visit_function

    def visit_ClassDef(self, node: ast.ClassDef) -> None:
        for expression in [*node.bases, *node.keywords, *node.decorator_list]:
            self.visit(expression)
        self.classes.append(node.name)
        for statement in node.body:
            self.visit(statement)
        self.classes.pop()

    def visit_Assign(self, node: ast.Assign) -> None:
        if not self.stack and len(node.targets) == 1 and isinstance(node.targets[0], ast.Name):
            self.assign_target = node.targets[0].id
            self.visit(node.value)
            self.assign_target = None
            return
        self.generic_visit(node)

    def visit_AnnAssign(self, node: ast.AnnAssign) -> None:
        if not self.stack and isinstance(node.target, ast.Name) and node.value is not None:
            self.assign_target = node.target.id
            self.visit(node.value)
            self.assign_target = None
            return
        self.generic_visit(node)

    # strings
    def _site(self, node: ast.AST, text: str) -> None:
        if IDENT.match(text):
            self._mention(text)
        found = _classify_text(text, self.tables)
        if found:
            self._record(node, found, whole_string=text)

    def _record(self, node: ast.AST, found: Sequence[tuple[str, str]], *, whole_string: str | None = None) -> None:
        text = whole_string
        if self.stack:
            unit = ".".join([*self.classes, *(name for name, _ in self.stack)])
            reach_name: str | None = self.stack[-1][0]
            guarded = any(flag for _, flag in self.stack)
        elif self.assign_target is not None:
            unit = self.assign_target
            # A whole-string constant that is just a table name is resolved into its users' f-strings instead.
            if self.constants.get(self.assign_target) == text and text in self.tables:
                return
            reach_name = self.assign_target
            guarded = False
        else:
            unit, reach_name, guarded = "<module>", None, False
        for table, kind in found:
            self.sites.append(_RawSite(table, kind, self.path, getattr(node, "lineno", 0), unit, reach_name, guarded))

    def visit_Constant(self, node: ast.Constant) -> None:
        if isinstance(node.value, str) and id(node) not in self.docstrings and id(node) not in self.handled:
            self._site(node, node.value)

    def visit_Call(self, node: ast.Call) -> None:
        """A table passed to a helper whose own SQL takes the table from a parameter (``_insert(c, "t", row)``)."""

        func = node.func
        name = func.id if isinstance(func, ast.Name) else (func.attr if isinstance(func, ast.Attribute) else None)
        kinds = sorted(self.dynamic.get(name, ())) if name else []
        for argument in [*node.args, *(keyword.value for keyword in node.keywords)]:
            if isinstance(argument, ast.Constant) and isinstance(argument.value, str):
                table = argument.value if argument.value in self.tables else None
            elif isinstance(argument, (ast.Name, ast.Attribute)):
                value = self.constants.get(argument.id if isinstance(argument, ast.Name) else argument.attr)
                table = value if value in self.tables else None
            else:
                table = None
            if table is None:
                continue
            if kinds:
                self._record(argument, [(table, kind) for kind in kinds])
                self.handled.add(id(argument))
            elif not isinstance(argument, ast.Constant):
                self._record(argument, [(table, "named")])
        self.generic_visit(node)

    def visit_JoinedStr(self, node: ast.JoinedStr) -> None:
        for value in node.values:
            if isinstance(value, ast.FormattedValue):
                self.visit(value.value)
        self._site(node, _fstring_text(node, self.constants))


@dataclass
class SourceScan:
    sites: list[Site]
    roles: dict[str, str]
    replayers: dict[str, str]  # table -> replayer name


def _replayers(src: Path) -> dict[str, str]:
    path = src / "learnloop/substrate/rebuild_orchestrator.py"
    if not path.exists():
        return {}
    owners: dict[str, str] = {}
    for node in ast.walk(ast.parse(path.read_text(encoding="utf-8"))):
        if isinstance(node, ast.Call) and isinstance(node.func, ast.Name) and node.func.id == REPLAYER_CLASS and node.args:
            name = node.args[0]
            if not (isinstance(name, ast.Constant) and isinstance(name.value, str)):
                continue
            for owned in node.args[1:2]:
                for constant in ast.walk(owned):
                    if isinstance(constant, ast.Constant) and isinstance(constant.value, str):
                        owners[constant.value] = name.value
    return owners


DYNAMIC_WRITE = re.compile(
    r"\b(?:INSERT(?:\s+OR\s+\w+)?\s+INTO|REPLACE\s+INTO|UPDATE(?:\s+OR\s+\w+)?|DELETE\s+FROM)\s+[\"`\[]?\s*\{\?\}", re.I
)
DYNAMIC_READ = re.compile(r"\b(?:FROM|JOIN)\s+[\"`\[]?\s*\{\?\}", re.I)


@dataclass
class _Prepass:
    #: module-level names bound to a table name, where every binding of the name across src agrees
    constants: dict[str, str]
    #: function name -> the kinds ("write", "read") of SQL it builds around a table taken from a parameter
    dynamic: dict[str, set[str]]


def _prepass(files: Sequence[tuple[str, str, ast.Module]], tables: frozenset[str]) -> _Prepass:
    bindings: dict[str, set[str]] = {}
    for _, _, tree in files:
        for name, value in _module_constants(tree).items():
            bindings.setdefault(name, set()).add(value)
    constants = {name: next(iter(values)) for name, values in bindings.items() if len(values) == 1 and next(iter(values)) in tables}
    dynamic: dict[str, set[str]] = {}
    for _, _, tree in files:
        local = {**constants, **_module_constants(tree)}
        for node in ast.walk(tree):
            if not isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
                continue
            for inner in ast.walk(node):
                if not isinstance(inner, ast.JoinedStr):
                    continue
                text = _fstring_text(inner, local)
                if not SQL_KEYWORD.search(text):
                    continue
                if DYNAMIC_WRITE.search(text):
                    dynamic.setdefault(node.name, set()).add("write")
                if DYNAMIC_READ.search(text):
                    dynamic.setdefault(node.name, set()).add("read")
    return _Prepass(constants=constants, dynamic=dynamic)


def scan_sources(src: Path, *, without: frozenset[str] = frozenset()) -> SourceScan:
    """Scan ``src``; ``without`` names files (relative to ``src``) to scan as if they were deleted."""

    roles = parse_roles(src)
    tables = frozenset(roles)
    raw: list[_RawSite] = []
    defs: dict[str, list[set[str]]] = {}
    seeds: set[str] = set()
    files: list[tuple[str, str, ast.Module]] = []
    for path in sorted(src.rglob("*.py")):
        if "__pycache__" in path.parts:
            continue
        relative = path.relative_to(src).as_posix()
        if relative in without:
            continue
        source = path.read_text(encoding="utf-8")
        files.append((relative, source, ast.parse(source, filename=relative)))
    prepass = _prepass(files, tables)
    for relative, source, tree in files:
        scanner = _FileScanner(relative, source, tree, tables, prepass)
        scanner.visit(tree)
        raw.extend(scanner.sites)
        seeds |= scanner.seeds
        for name, refs in scanner.defs:
            defs.setdefault(name, []).append(refs)
    reached = set(seeds)
    frontier = sorted(reached)
    while frontier:
        name = frontier.pop()
        for refs in defs.get(name, ()):
            for ref in refs - reached:
                reached.add(ref)
                frontier.append(ref)
    sites = sorted(
        {
            Site(
                table=s.table, kind=s.kind, path=s.path, line=s.line, unit=s.unit,
                reached=s.reach_name is None or s.reach_name in reached,
                guarded=s.guarded, category=_category(s.path),
            )
            for s in raw
        },
        key=lambda s: (s.table, s.kind, s.path, s.line, s.unit),
    )
    return SourceScan(sites=sites, roles=roles, replayers=_replayers(src))


