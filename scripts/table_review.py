# --- the role registry and the migrations --------------------------------------------------------------------------


def parse_roles(src: Path) -> dict[str, str]:
    """``_TABLE_ROLE_ITEMS`` from ``src/learnloop/db/table_roles.py``, read by AST (no import)."""

    tree = ast.parse((src / "learnloop/db/table_roles.py").read_text(encoding="utf-8"))
    for node in tree.body:
        target = node.target if isinstance(node, ast.AnnAssign) else (node.targets[0] if isinstance(node, ast.Assign) else None)
        if isinstance(target, ast.Name) and target.id == "_TABLE_ROLE_ITEMS" and isinstance(node.value, ast.Tuple):
            roles: dict[str, str] = {}
            for item in node.value.elts:
                assert isinstance(item, ast.Tuple) and len(item.elts) == 2
                name, role = item.elts
                assert isinstance(name, ast.Constant) and isinstance(role, ast.Attribute)
                roles[str(name.value)] = role.attr
            return roles
    raise ValueError("no _TABLE_ROLE_ITEMS in table_roles.py")


@dataclass
class MigrationFacts:
    first: str | None = None
    seeded_by: list[str] = field(default_factory=list)
    trigger_written_by: list[str] = field(default_factory=list)


def _strip_sql_comments(text: str) -> str:
    return "\n".join(line.split("--", 1)[0] for line in text.splitlines())


def migration_facts(migrations: Path, tables: Iterable[str]) -> dict[str, MigrationFacts]:
    """The migration that first creates each table, and the migrations that write rows into it."""

    wanted = set(tables)
    facts = {table: MigrationFacts() for table in sorted(wanted)}
    for path in sorted(migrations.glob("*.sql")):
        text = _strip_sql_comments(path.read_text(encoding="utf-8"))
        number = path.stem
        for match in CREATE_TABLE.finditer(text):
            table = match.group(1)
            if table in wanted and facts[table].first is None:
                facts[table].first = number
        triggers = [m.group(0) for m in TRIGGER.finditer(text)]
        outside = TRIGGER.sub(" ", text)
        for match in MIGRATION_WRITE.finditer(outside):
            table = match.group(1)
            if table in wanted and number not in facts[table].seeded_by:
                facts[table].seeded_by.append(number)
        for body in triggers:
            for match in MIGRATION_WRITE.finditer(body):
                table = match.group(1)
                if table in wanted and number not in facts[table].trigger_written_by:
                    facts[table].trigger_written_by.append(number)
    return facts


def foreign_key_children(migrations: Path, tables: Iterable[str]) -> dict[str, list[str]]:
    """Each table's FK children at the migration head, from the migrations applied to an in-memory database."""

    connection = sqlite3.connect(":memory:")
    try:
        for path in sorted(migrations.glob("*.sql")):
            connection.executescript(path.read_text(encoding="utf-8"))
        wanted = set(tables)
        children: dict[str, set[str]] = {table: set() for table in wanted}
        for child in sorted(wanted):
            for row in connection.execute(f"PRAGMA foreign_key_list({_quote(child)})"):
                parent = str(row[2])
                if parent in children and parent != child:
                    children[parent].add(child)
    finally:
        connection.close()
    return {table: sorted(names) for table, names in children.items()}


