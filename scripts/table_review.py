"""The table review list (refactor strategy v3 §2.5, step J1): every table, for the owner to answer.

For each table in ``db/table_roles.py`` it gathers two kinds of facts.

**Code facts** (tracked, ``--public``): the role, the migration that first creates it, its SQL writers and readers in
``src/`` with file:line, whether each is reached by name, the replayer or upgrade that touches it, doctor and sync
mentions, a class (derived, live, retired but still read, dead), whether its readers tolerate its absence, and flags.
With ``--base-src`` (an older ``src/`` tree, e.g. before arc C's removals) it also says what the removals between the
two trees took from each table.

**Data facts** (private, ``--private-out``): per database copy, each table's row count, newest date and bytes, and
each database file's size. The tracked output carries only aggregates that name no vault: how many copies hold rows.

How the code facts are found, and their limits (they are a static scan, not a proof):

- Every string constant and f-string in ``src/`` (docstrings excluded), with f-string names resolved to module-level
  string constants. A string is SQL when it has an upper-case SQL keyword. Writers are ``INSERT``/``REPLACE INTO``,
  ``UPDATE`` and ``DELETE FROM``; readers are ``FROM``/``JOIN`` and ``PRAGMA table_info``. A string that is exactly a
  table's name is a *named* site: a dynamic reader (a table list fed to ``SELECT ... FROM {table}``), a guard, or a
  list entry. SQL built from other variables is missed.
- *Reached* is name reachability, not import reachability: names used at module or class level (registries, Typer
  decorators, ``__all__``), every decorated function and every dunder seed it, and a reached function reaches every
  function whose name it mentions (as a name, an attribute or an identifier-like string). Name collisions make it
  over-approximate: "unreached" is a strong claim, "reached" a weak one. Tests are not scanned, so a function only
  tests call is unreached.
- *Tolerates absence* is read off the reader's own function (and its enclosing ones): a ``sqlite_master`` query, a
  ``*table_exists``/``*table_present``/``has_table(s)``/``_table`` call, ``PRAGMA table_info``, or an
  ``OperationalError`` handler. A guard in a caller is missed, so "no" can be wrong; "yes" is a guard seen.

Read-only and deterministic: databases are opened with ``file:...?mode=ro&immutable=1``; nothing is written beside
them; the output is sorted and carries no clock. It refuses a path under ``~/learnloop-vaults``,
``~/learnloop-retired``, ``~/learnloop-books`` or ``~/learnloop-backups``: make a copy with
``learnloop.db.copies.copy_tree_with_databases`` first. Standalone (it imports nothing from ``learnloop``), so it
reads an older tree as easily as this one::

    uv run python scripts/table_review.py \\
        --copies fixtures-local/table-review/copies/arxiv_v2 fixtures-local/table-review/copies/linear_algebra \\
        --base-src fixtures-local/table-review/base/src \\
        --private-out fixtures-local/table-review --public docs/reviews/table-review-2026-11-11.md

``--public`` rewrites only the text between the ``table-review:begin`` and ``table-review:end`` markers of an existing
file (or writes the generated part alone to a new one), so the hand-written review around it stays.
"""

