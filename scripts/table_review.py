def _uses(sites: Sequence[Site], *, exclude: frozenset[str] = frozenset()) -> dict[str, list[Site]]:
    """Reached uses by kind; bare names in the list files are never uses."""

    out: dict[str, list[Site]] = {"write": [], "upgrade_write": [], "read": [], "named": []}
    # A bare name beside SQL on the same table in the same function is that function's guard, not another reader.
    with_sql = {(site.path, site.unit) for site in sites if site.kind != "named"}
    for site in sites:
        if not site.reached or site.category in exclude:
            continue
        if site.kind == "named":
            if site.category not in LIST_FILES.values() and (site.path, site.unit) not in with_sql:
                out["named"].append(site)
        elif site.kind == "write":
            out["upgrade_write" if site.category == "upgrade" else "write"].append(site)
        else:
            out["read"].append(site)
    return out


def classify(role: str, sites: Sequence[Site], migration: MigrationFacts, *, exclude: frozenset[str] = frozenset()) -> str:
    if role == "DERIVED":
        return "derived and rebuildable"
    uses = _uses(sites, exclude=exclude)
    readers = uses["read"] + uses["named"]
    if not (uses["write"] or uses["upgrade_write"] or readers or migration.trigger_written_by):
        return "dead"
    if uses["write"] or migration.trigger_written_by:
        return "live"
    if migration.seeded_by and readers:
        return "live"
    return "retired but still read"


@dataclass
class TableFacts:
    table: str
    role: str
    klass: str
    feature: str
    writers: list[str]
    readers: list[str]
    writer_count: int
    reader_count: int
    unreached_writers: int
    replayer: str
    upgrades: list[str]
    doctor: bool
    sync: bool
    tolerates_absence: str
    flags: list[str]
    fk_children: list[str] = field(default_factory=list)
    base_class: str | None = None
    removed_sites: int = 0


def _sites_by_table(scan: SourceScan | None) -> dict[str, list[Site]]:
    out: dict[str, list[Site]] = {}
    for site in scan.sites if scan is not None else ():
        out.setdefault(site.table, []).append(site)
    return out


def _tolerance(readers: Sequence[Site]) -> str:
    if not readers:
        return "-"
    guarded = sum(1 for site in readers if site.guarded)
    if guarded == len(readers):
        return f"yes ({guarded}/{len(readers)})"
    return f"partly ({guarded}/{len(readers)})" if guarded else f"no (0/{len(readers)})"


def _site_key(site: Site) -> tuple[str, str, str, str]:
    return (site.kind, site.path, site.unit, site.table)


def table_facts(
    scan: SourceScan,
    migrations: Mapping[str, MigrationFacts],
    base: SourceScan | None = None,
    what_if: Mapping[str, SourceScan] | None = None,
    fk_children: Mapping[str, Sequence[str]] | None = None,
) -> list[TableFacts]:
    """One row per table. ``what_if`` maps an in-flight step to the scan made as if its modules were gone."""

    by_table: dict[str, list[Site]] = {table: [] for table in scan.roles}
    for site in scan.sites:
        by_table[site.table].append(site)
    base_by_table = _sites_by_table(base)
    what_if_by_table = {step: _sites_by_table(other) for step, other in (what_if or {}).items()}
    out: list[TableFacts] = []
    for table in sorted(scan.roles):
        role = scan.roles[table]
        sites = by_table[table]
        migration = migrations.get(table, MigrationFacts())
        klass = classify(role, sites, migration)
        uses = _uses(sites)
        readers = uses["read"] + uses["named"]
        writers = uses["write"] + uses["upgrade_write"]
        flags: list[str] = []
        if role == "COMPAT" and uses["write"]:
            flags.append("role COMPAT, written on a reached path")
        if klass == "live" and uses["write"] and not readers:
            flags.append("write-only")
        if not uses["write"] and uses["upgrade_write"]:
            flags.append("written only by an upgrade")
        if migration.seeded_by:
            flags.append("rows written by migration " + ", ".join(m.split("_", 1)[0] for m in migration.seeded_by))
        if migration.trigger_written_by:
            flags.append("trigger-written (migration " + ", ".join(m.split("_", 1)[0] for m in migration.trigger_written_by) + ")")
        unreached_writers = sum(1 for s in sites if s.kind == "write" and not s.reached)
        sql_sites = [s for s in sites if s.kind != "named"]
        if klass == "dead":
            unreached = [s for s in sql_sites if not s.reached]
            flags.append(f"every SQL site unreached ({len(unreached)})" if unreached else "no SQL in src")
        elif unreached_writers and not uses["write"]:
            flags.append(f"every code writer unreached ({unreached_writers})")
        for step, other in sorted(what_if_by_table.items()):
            other_class = classify(role, other.get(table, []), migration)
            if other_class != klass:
                flags.append(f"re-check after {step} (without its modules: {other_class})")
        rebuild_units = sorted({
            s.unit.rsplit(".", 1)[-1] for s in sites
            if s.category == "rebuild" or s.unit.rsplit(".", 1)[-1] == PER_LO_RESET
        })
        replayer = scan.replayers.get(table, "")
        if not replayer and PER_LO_RESET in rebuild_units:
            replayer = "per-LO replay reset"
        if not replayer and rebuild_units:
            replayer = "read by rebuild (" + ", ".join(rebuild_units[:2]) + ")"
        upgrades = sorted({Path(s.path).stem for s in sites if s.category == "upgrade"})
        facts = TableFacts(
            table=table, role=role, klass=klass, feature=migration.first or "-",
            writers=[s.where for s in writers[:MAX_SITES_SHOWN]], readers=[s.where for s in readers[:MAX_SITES_SHOWN]],
            writer_count=len(writers), reader_count=len(readers), unreached_writers=unreached_writers,
            replayer=replayer, upgrades=upgrades,
            doctor=any(s.category == "doctor" for s in sites), sync=any(s.category == "sync" for s in sites),
            tolerates_absence=_tolerance(readers), flags=flags,
            fk_children=list((fk_children or {}).get(table, ())),
        )
        if facts.fk_children:
            flags.append(f"FK parent of {len(facts.fk_children)} table(s)")
        if base is not None:
            base_sites = base_by_table.get(table, [])
            facts.base_class = classify(base.roles.get(table, role), base_sites, migration)
            tip_keys = {_site_key(s) for s in sites}
            removed = {_site_key(s) for s in base_sites if s.kind != "named"} - tip_keys
            facts.removed_sites = len(removed)
            if facts.base_class != klass:
                flags.append(f"class changed since the base ({facts.base_class} -> {klass})")
            if removed:
                last = " (its last)" if not sql_sites else ""
                flags.append(f"removals since the base: {len(removed)} SQL site(s){last}")
        out.append(facts)
    return out


# --- the copies (private) ------------------------------------------------------------------------------------------


def _quote(name: str) -> str:
    return '"' + name.replace('"', '""') + '"'


def copy_facts(copy_root: Path, tables: Iterable[str]) -> dict[str, Any]:
    """Row counts, newest dates and bytes per table, and database file sizes, for one vault copy."""

    database = copy_root / "state.sqlite"
    if not database.is_file():
        raise SystemExit(f"{copy_root}: no state.sqlite at the copy's root")
    files = {
        path.relative_to(copy_root).as_posix(): path.stat().st_size
        for path in sorted(copy_root.rglob("*"))
        if path.is_file() and (path.suffix in {".sqlite", ".db"} or path.name.endswith((".sqlite-wal", ".sqlite-journal")))
    }
    connection = sqlite3.connect(read_only_uri(database), uri=True)
    try:
        present = {row[0] for row in connection.execute("SELECT name FROM sqlite_master WHERE type='table'")}
        head = None
        if "schema_migrations" in present:
            head = connection.execute("SELECT MAX(version) FROM schema_migrations").fetchone()[0]
        owners = dict(connection.execute("SELECT name, tbl_name FROM sqlite_master WHERE type IN ('table','index')"))
        sizes: Counter[str] = Counter()
        try:
            for name, size in connection.execute("SELECT name, SUM(pgsize) FROM dbstat GROUP BY name"):
                sizes[owners.get(name, name)] += int(size or 0)
        except sqlite3.OperationalError:  # dbstat not compiled in: sizes are left out
            sizes.clear()
        per_table: dict[str, Any] = {}
        for table in sorted(tables):
            if table not in present:
                per_table[table] = {"present": False}
                continue
            rows = int(connection.execute(f"SELECT COUNT(*) FROM {_quote(table)}").fetchone()[0])
            newest = None
            if rows:
                columns = [str(c[1]) for c in connection.execute(f"PRAGMA table_info({_quote(table)})")]
                dated = [c for c in columns if c.endswith(("_at", "_date", "_day")) or c in {"timestamp", "date", "day"}]
                for column in dated:
                    value = connection.execute(
                        f"SELECT MAX({_quote(column)}) FROM {_quote(table)} WHERE typeof({_quote(column)})='text'"
                    ).fetchone()[0]
                    if isinstance(value, str) and DATE.match(value) and (newest is None or value > newest):
                        newest = value
            per_table[table] = {"present": True, "rows": rows, "newest": newest, "bytes": sizes.get(table)}
    finally:
        connection.close()
    return {"migration_head": head, "files": files, "tables": per_table}


# --- output --------------------------------------------------------------------------------------------------------


def _cell(values: Sequence[str], total: int) -> str:
    if not values:
        return "-"
    shown = ", ".join(f"`{v}`" for v in values)
    return shown + (f" +{total - len(values)}" if total > len(values) else "")


def _copies_cell(table: str, copies: Mapping[str, Mapping[str, Any]]) -> str:
    if not copies:
        return "-"
    entries = [c["tables"][table] for c in copies.values()]
    present = [e for e in entries if e["present"]]
    if not present:
        return "absent"
    holding = sum(1 for e in present if e["rows"])
    absent = len(entries) - len(present)
    return f"{holding} of {len(entries)}" + (f" ({absent} absent)" if absent else "")


CLASS_ORDER = ("dead", "retired but still read", "live", "derived and rebuildable")


def public_markdown(facts: Sequence[TableFacts], copies: Mapping[str, Mapping[str, Any]], *, src_label: str, base_label: str | None) -> str:
    """The tracked part: code facts and aggregates that name no vault."""

    lines: list[str] = [BEGIN, ""]
    count = Counter(f.klass for f in facts)
    roles = sorted({f.role for f in facts})
    lines.append(f"Scanned: `{src_label}`" + (f"; removals compared with `{base_label}`" if base_label else "") + f". {len(facts)} tables.")
    lines.append("")
    lines += ["| Class | Tables |", "|---|---:|"]
    lines += [f"| {k} | {count.get(k, 0)} |" for k in CLASS_ORDER]
    lines.append("")
    lines += ["| Role | " + " | ".join(CLASS_ORDER) + " |", "|---|" + "---:|" * len(CLASS_ORDER)]
    for role in roles:
        row = Counter(f.klass for f in facts if f.role == role)
        total = sum(row.values())
        lines.append(f"| {role} ({total}) | " + " | ".join(str(row.get(k, "")) or "" for k in CLASS_ORDER) + " |")
    if copies:
        empty = sum(1 for f in facts if _copies_cell(f.table, copies).startswith("0 of"))
        absent = sum(1 for f in facts if _copies_cell(f.table, copies) == "absent")
        lines += ["", f"Across the {len(copies)} copies: {empty} tables are empty in every copy that has them, and {absent} are absent from every copy (added after the copies' migration head)."]
    lines += [
        "",
        "Paths are relative to `src/learnloop/` (others to `src/`). Writers and readers are reached sites only, first "
        f"{MAX_SITES_SHOWN} shown. \"Copies\" is how many copies hold any row.",
        "",
        "| table | role | class | writers | readers | replayer / upgrade | doctor / sync | feature | tolerates absence | copies | flags |",
        "|---|---|---|---|---|---|---|---|---|---|---|",
    ]
    order = {k: i for i, k in enumerate(CLASS_ORDER)}
    for f in sorted(facts, key=lambda f: (order[f.klass], f.table)):
        replay = "; ".join(x for x in [f.replayer, ", ".join(f"`{u}`" for u in f.upgrades)] if x) or "-"
        mentions = ", ".join(x for x, on in (("doctor", f.doctor), ("sync", f.sync)) if on) or "-"
        lines.append(
            f"| `{f.table}` | {f.role} | {f.klass} | {_cell(f.writers, f.writer_count)} | {_cell(f.readers, f.reader_count)} "
            f"| {replay} | {mentions} | {f.feature} | {f.tolerates_absence} | {_copies_cell(f.table, copies)} | {'; '.join(f.flags) or '-'} |"
        )
    lines += ["", END]
    return "\n".join(lines) + "\n"


def write_public(path: Path, generated: str) -> None:
    if path.exists():
        text = path.read_text(encoding="utf-8")
        if BEGIN in text and END in text:
            head, rest = text.split(BEGIN, 1)
            _, tail = rest.split(END, 1)
            path.write_text(head + generated.rstrip("\n") + tail, encoding="utf-8")
            return
    path.write_text(generated, encoding="utf-8")


def private_markdown(facts: Sequence[TableFacts], copies: Mapping[str, Mapping[str, Any]]) -> str:
    names = sorted(copies)
    lines = ["# Table review: private counts (gitignored; never commit)", ""]
    lines += ["| copy | migration head | database files (bytes) |", "|---|---|---|"]
    for name in names:
        files = ", ".join(f"{k}: {v}" for k, v in copies[name]["files"].items())
        lines.append(f"| {name} | {copies[name]['migration_head']} | {files} |")
    lines += ["", "| table | class | " + " | ".join(f"{n} rows | {n} newest | {n} bytes" for n in names) + " |"]
    lines.append("|---|---|" + "---|---|---|" * len(names))
    for f in facts:
        cells = []
        for name in names:
            entry = copies[name]["tables"][f.table]
            if not entry["present"]:
                cells += ["absent", "", ""]
            else:
                cells += [str(entry["rows"]), (entry["newest"] or "")[:10], str(entry["bytes"] if entry["bytes"] is not None else "")]
        lines.append(f"| `{f.table}` | {f.klass} | " + " | ".join(cells) + " |")
    return "\n".join(lines) + "\n"


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.split("\n\n", 1)[0])
    parser.add_argument("--src", type=Path, default=ROOT / "src")
    parser.add_argument("--migrations", type=Path, default=ROOT / "migrations")
    parser.add_argument("--base-src", type=Path, help="an older src/ tree to compare removals with")
    parser.add_argument("--copies", type=Path, nargs="*", default=[], help="vault copies, each with state.sqlite at its root")
    parser.add_argument("--private-out", type=Path, help="directory for the private JSON and Markdown (gitignored)")
    parser.add_argument("--public", type=Path, help="the tracked review file to fill between its markers")
    parser.add_argument("--src-label", default="src/")
    parser.add_argument("--base-label")
    args = parser.parse_args(argv)
    copies_paths = [refuse_live(p) for p in args.copies]
    scan = scan_sources(args.src)
    base = scan_sources(args.base_src) if args.base_src else None
    what_if = {step: scan_sources(args.src, without=files) for step, files in IN_FLIGHT.items()}
    migrations = migration_facts(args.migrations, scan.roles)
    facts = table_facts(scan, migrations, base, what_if, foreign_key_children(args.migrations, scan.roles))
    copies = {p.name: copy_facts(p, scan.roles) for p in copies_paths}
    if args.public:
        write_public(args.public, public_markdown(facts, copies, src_label=args.src_label, base_label=args.base_label))
    if args.private_out:
        out = refuse_live(args.private_out)
        out.mkdir(parents=True, exist_ok=True)
        payload = {"tables": [asdict(f) for f in facts], "copies": copies, "sites": [asdict(s) for s in scan.sites]}
        (out / "table-review.json").write_text(json.dumps(payload, indent=1, sort_keys=True) + "\n", encoding="utf-8")
        if copies:
            (out / "table-review-private.md").write_text(private_markdown(facts, copies), encoding="utf-8")
    if not (args.public or args.private_out):
        sys.stdout.write(public_markdown(facts, copies, src_label=args.src_label, base_label=args.base_label))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
