def refuse_live(path: Path, home: Path | None = None) -> Path:
    """Return ``path`` resolved, refusing the owner's live, retired, book and backup directories."""

    resolved = Path(path).expanduser().resolve()
    home = (home or Path.home()).resolve()
    for name in REFUSED_HOME_DIRS:
        refused = home / name
        if resolved == refused or refused in resolved.parents:
            raise SystemExit(
                f"refusing {resolved}: it is under ~/{name}. Copy it with "
                "learnloop.db.copies.copy_tree_with_databases and pass the copy."
            )
    return resolved


