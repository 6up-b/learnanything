def _textbook_rk4(f, x, y, h, steps):
    """An independent RK4 (the textbook's), for dx/dt, dy/dt = f(x, y)."""

    out = [(x, y)]
    for _ in range(steps):
        a = f(x, y)
        b = f(x + h / 2 * a[0], y + h / 2 * a[1])
        c = f(x + h / 2 * b[0], y + h / 2 * b[1])
        d = f(x + h * c[0], y + h * c[1])
        x, y = x + h / 6 * (a[0] + 2 * b[0] + 2 * c[0] + d[0]), y + h / 6 * (a[1] + 2 * b[1] + 2 * c[1] + d[1])
        out.append((x, y))
    return out


def test_rk4_is_the_textbook_integrator_step_for_step_and_fourth_order():
    spec = PC.damped_oscillator()
    compiled = S.parse_spec(spec)
    data = S.evaluate_figure(compiled, {"w": 1, "c": 0})["panels"][0]
    reference = _textbook_rk4(lambda x, y: (y, -1 * 1 * x - 0 * y), 1.0, 0.0, 10 / 200, 200)
    assert [(x, y) for x, y in zip(data["x"], data["y"])] == pytest.approx(reference, rel=1e-14, abs=1e-15)
    assert data["t"][-1] == pytest.approx(10.0)
    # The undamped oscillator is x = cos t: RK4 at h = 0.05 is within 1e-6.
    assert abs(data["x"][-1] - math.cos(10)) < 1e-6 and abs(data["y"][-1] + math.sin(10)) < 1e-6


def test_the_same_spec_sampled_more_finely_converges_at_fourth_order():
    errors = []
    for steps in (50, 100):
        spec = PC.damped_oscillator()
        spec["panels"][0]["steps"] = steps
        data = S.evaluate_figure(S.parse_spec(spec), {"w": 1, "c": 0})["panels"][0]
        errors.append(abs(data["x"][-1] - math.cos(10)))
    assert 12 < errors[0] / errors[1] < 20  # halving h cuts the error about 16 times


def test_an_iterated_map_is_its_recurrence():
    data = S.evaluate_figure(S.parse_spec(PC.gradient_descent()), {"lr": 0.1, "a": 1, "b": 2})["panels"][0]
    x, y = 1.5, 1.8
    for k in range(1, 6):
        x, y = x - 0.1 * 2 * 1 * x, y - 0.1 * 2 * 2 * y
        assert (data["x"][k], data["y"][k], data["k"][k]) == (x, y, float(k))


def test_a_path_is_cut_where_it_leaves_its_plot_and_never_drawn_past_it():
    data = S.evaluate_figure(S.parse_spec(PC.growth_leaves_plot()), {"g": 1})["panels"][0]
    assert data["stopped"] == S.STOP_LEFT
    low, high = S.escape_box(S.Axis(var="x", min=-2, max=2))
    assert all(low <= value <= high for value in data["x"])
    assert len(data["x"]) < 101


