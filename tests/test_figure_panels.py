def test_the_corpus_covers_every_panel_kind_and_every_stop():
    kinds = {kind for figure in CORPUS["figures"] for kind in S.advanced_kinds(figure["spec"])}
    assert kinds == set(S.ADVANCED_KINDS)
    stops = {panel.get("stopped") for figure in CORPUS["figures"] for data in figure["expected"]
             for panel in data["panels"]}
    assert {None, S.STOP_LEFT, S.STOP_NOT_FINITE, S.STOP_OUTSIDE} <= stops
    specs = [figure["spec"] for figure in CORPUS["figures"]]
    panels = [panel for spec in specs for panel in spec["panels"]]
    assert any(panel.get("heatmap") for panel in panels), "a vector field over a heat map"
    assert any(panel.get("time") for panel in panels), "a forced system reading t"
    assert any(panel.get("contours") for panel in panels)
    assert any("sum(" in panel.get("expr", "") for panel in panels), "attention-like weights by sum"
    assert any(figure["exact"] and figure["spec"]["panels"][0]["kind"] == "trajectory_2d"
               for figure in CORPUS["figures"]), "an exact RK4 parity case"


