def test_the_work_cap_counts_a_sums_terms():
    # 6 x 6 points, a sum of 6 terms of a 9-node body: well inside the cap ...
    S.parse_spec(PC.attention_weights())
    # ... but a sum of 10,001 terms at 41 x 41 points is far past it.
    spec = PC._spec([{"kind": "heatmap_2d", "x": {"var": "x", "min": 0, "max": 1}, "y": {"var": "y", "min": 0, "max": 1},
                      "expr": "sum(m*x, m, 1, 10000)"}], [PC._param("a", 0, 1, 0.1, 0.5)])
    with pytest.raises(S.SpecError) as caught:
        S.parse_spec(spec)
    assert "more computation than a figure may do" in caught.value.problems[0]


