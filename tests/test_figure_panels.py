def test_switched_off_the_panels_are_refused_at_parse_and_named():
    for make in (PC.quadratic_landscape, PC.gradient_field, PC.damped_oscillator, PC.gradient_descent):
        spec = make()
        with pytest.raises(S.SpecError) as caught:
            S.parse_spec(spec, advanced=False)
        assert "switched off (figures.advanced_panels_enabled)" in caught.value.problems[0]
        S.parse_spec(spec)  # on: accepted
    assert S.parse_spec(FC.flagship_spec(), advanced=False).panels  # RW5a's panels are unaffected


