"""RW5d P2's parity corpus (spec_reader_show_me_figures_v1 G-SM9): one engine, two hosts.

Each case is a sketch and a script of engine calls; the corpus stores the
exact text each read returned in the sidecar's wasmtime runner. The desktop's
engine host (``sketchParity.test.ts``, the same ``sketch-engine.wasm`` under
V8's WebAssembly) must return the same text, byte for byte, which is what
makes a drawn value equal a verified value.

``verified`` (fix round 4, the independent sandbox review) holds programs and
the sketch view the sidecar sends for them (the verifier's checks, its read
schedule and the digest of every read it checked, camelized as the desktop
receives them): ``sketchSandboxReview.test.tsx`` plays each in the desktop and
its own digests must equal these.

Regenerate after an intended engine or corpus change::

    uv run python -m tests.sketch_parity_corpus
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from learnloop.figures import sketch as K
from learnloop.figures import sketch_verify as SV
from learnloop.figures.sketch_engine import ENGINE_SHA256, SketchEngine
from learnloop_sidecar.dto import to_camel
from tests import sketch_fixtures as F

PATH = (Path(__file__).resolve().parents[1] / "apps" / "learnloop-tauri" / "src" / "screens" / "reader" / "figures"
        / "sketch" / "sketchParityCorpus.json")


def _script(program: dict[str, Any]) -> list[dict[str, Any]]:
    """Init at the defaults and at each parameter's max, read, step in uneven
    chunks, read again; and a second seed."""

    defaults = {p["name"]: float(p["default"]) for p in program.get("parameters") or []}
    highs = {p["name"]: float(p["max"]) for p in program.get("parameters") or []}
    clock = program.get("clock")
    calls: list[dict[str, Any]] = []
    for params, seed in ((defaults, 1), (highs, 1), (defaults, 99)):
        calls.append({"op": "init", "params": params, "seed": seed})
        calls += [{"op": "view", "params": params, "index": 0}, {"op": "probes", "params": params, "index": 0}]
        if clock:
            index = 0
            for count in (1, 4, 7):
                calls.append({"op": "step", "params": params, "dt": clock["dt"], "index": index, "count": count})
                index += count
                calls += [{"op": "view", "params": params, "index": index},
                          {"op": "probes", "params": params, "index": index}]
    return calls


def build() -> dict[str, Any]:
    cases = []
    for name, program in F.good():
        calls = _script(program)
        with SketchEngine() as engine:
            engine.load(program["code"])
            for call in calls:
                if call["op"] == "init":
                    engine.init(call["params"], call["seed"])
                elif call["op"] == "step":
                    engine.step(call["params"], call["dt"], index=call["index"], count=call["count"])
                elif call["op"] == "view":
                    call["expect"] = engine.view_text(call["params"], index=call["index"])
                else:
                    call["expect"] = engine.probes_text(call["params"], index=call["index"])
        cases.append({"name": name, "code": program["code"], "calls": calls})
    verified = []
    for name, program in (("random walk", F.walk()), ("marks when read", F.marks_when_read())):
        report = SV.verify_sketch(K.parse_sketch(program)).as_dict()
        assert report["outcome"] == "illustrative", report["reason"]
        verified.append({"name": name, "program": program, "sketch": to_camel({
            "engine_sha256": ENGINE_SHA256, "seed": SV.VERIFY_SEED, "checks": report["checks"],
            "not_covered": report["not_covered"], "unnamed_elements": report["unnamed_elements"],
            "settings": report["settings"], "read_steps": report["read_steps"], "tested": report["tested"]})})
    return {"about": "RW5d P2 parity corpus (G-SM9): the text each read returns in the pinned engine; generated by "
                     "tests/sketch_parity_corpus.py in the sidecar, replayed by sketchParity.test.ts in the desktop.",
            "engine_sha256": ENGINE_SHA256, "cases": cases, "verified": verified}


def write() -> None:
    PATH.write_text(json.dumps(build(), indent=1, ensure_ascii=False) + "\n", encoding="utf-8")


if __name__ == "__main__":
    write()
