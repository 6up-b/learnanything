"""Reader RW5a: the figure grammar's Python evaluator on the golden corpus (spec §8.2; G21, G22, G45).

The same corpus (``figureGoldenCorpus.json``, generated by
``tests/figure_corpus.py``) is run by ``figureGrammar.test.ts``: both
evaluators agree on every value within 1e-9 relative (1e-6 for integrals),
the parsers agree on every accepted and rejected input, and every panel kind
evaluates to the same data.
"""

from __future__ import annotations

import ast
import json
import math
import random
from pathlib import Path

import pytest

from learnloop.figures import grammar as G
from learnloop.figures import spec as S
from tests import figure_corpus as FC

CORPUS = json.loads(FC.CORPUS_PATH.read_text(encoding="utf-8"))
FIGURES_PACKAGE = Path(__file__).resolve().parents[1] / "src" / "learnloop" / "figures"


def _num(value):
    if isinstance(value, str):
        return {"nan": math.nan, "inf": math.inf, "-inf": -math.inf}[value]
    return value


def _close(actual: float, expected: float, tolerance: float) -> bool:
    if expected is None:
        return actual is None
    if actual is None:
        return False
    if math.isnan(expected):
        return math.isnan(actual)
    if math.isinf(expected):
        return actual == expected
    return abs(actual - expected) <= tolerance * max(1.0, abs(actual), abs(expected))


def test_the_corpus_file_is_the_cases_as_generated():
    """The JSON both suites read is exactly what tests/figure_corpus.py builds."""

    assert FC.CORPUS_PATH.read_text(encoding="utf-8") == FC.render()


def test_the_corpus_covers_every_construct_and_panel_kind():
    seen: set[str] = set()
    for case in CORPUS["expressions"]:
        node = G.parse(case["expr"])
        for definition in case["definitions"]:
            node_list = list(G.walk(G.parse(definition["expr"])))
            seen |= {child.kind for child in node_list} | {child.text for child in node_list if child.kind == "call"}
            seen |= {child.op for child in node_list if child.op}
        nodes = list(G.walk(node))
        seen |= {child.kind for child in nodes}
        seen |= {child.text for child in nodes if child.kind == "call"}
        seen |= {child.op for child in nodes if child.op}
        seen |= {child.text for child in nodes if child.kind == "name" and child.text in G.CONSTANTS}
    expected = {"num", "name", "neg", "bin", "call", "piecewise", "integral", "sum", "cmp", "and", "or",
                "+", "-", "*", "/", "^", "<", "<=", ">", ">=", "==", "!=", "pi", "e", *G.FUNCTIONS}
    assert expected <= seen, expected - seen
    kinds = {panel["kind"] for figure in CORPUS["figures"] for panel in figure["spec"]["panels"]}
    assert kinds == {"function_plot", "pmf_bars", "linear_map_2d", "readout"}
    shaded = [figure for figure in CORPUS["figures"]
              if any(panel.get("shade") for panel in figure["spec"]["panels"])]
    highlighted = [figure for figure in CORPUS["figures"]
                   if any(panel.get("highlight") for panel in figure["spec"]["panels"])]
    assert shaded and highlighted
    assert {"two_sided_exponential", "two_sided_exponential_half_negative_control"} <= {
        figure["id"] for figure in CORPUS["figures"]}


@pytest.mark.parametrize("case", CORPUS["expressions"], ids=lambda case: case["id"])
def test_expression_values(case):
    defs = {d["name"]: G.parse(d["expr"]) for d in case["definitions"]}
    value = G.evaluate(G.parse(case["expr"]), case["env"], defs)
    assert _close(value, _num(case["expected"]), 1e-12)
    if case["reference"] is not None:
        tolerance = FC.INTEGRAL if case["integral"] else FC.RELATIVE
        assert _close(value, _num(case["reference"]), tolerance), (value, case["reference"])


@pytest.mark.parametrize("case", CORPUS["rejected"], ids=lambda case: case["id"])
def test_rejected_inputs(case):
    if case["stage"] == "parse":
        with pytest.raises(G.GrammarError):
            G.parse(case["expr"])
        return
    node = G.parse(case["expr"])
    defs = {d["name"]: G.parse(d["expr"]) for d in case["definitions"]}
    with pytest.raises(G.GrammarError):
        G.check_names(node, known=frozenset(case["known"]), definitions=defs)
        missing = S.expanded_free(node, defs) - set(case["known"])
        if missing:
            raise G.GrammarError(f"unbound {missing}")


@pytest.mark.parametrize("case", CORPUS["figures"], ids=lambda case: case["id"])
def test_figure_panels(case):
    compiled = S.parse_spec(case["spec"])
    for params, expected in zip(case["params"], case["expected"]):
        assert S.evaluate_figure(compiled, params) == expected
    for index, outcome in enumerate(case["predictions"]):
        assert S.prediction_outcome(compiled, index) == outcome


@pytest.mark.parametrize("case", CORPUS["rejected_figures"], ids=lambda case: case["id"])
def test_rejected_figures(case):
    with pytest.raises(S.SpecError):
        S.parse_spec(case["spec"])


def test_fuzz_verdicts():
    known = frozenset(CORPUS["fuzz"]["known"]) | set(CORPUS["fuzz"]["bound"])
    for case in CORPUS["fuzz"]["cases"]:
        try:
            node = G.parse(case["expr"])
            G.check_names(node, known=known, definitions={})
            if not S.expanded_free(node, {}) <= set(CORPUS["fuzz"]["known"]):
                raise G.GrammarError("unbound")
            accepted, value = True, G.evaluate(node, CORPUS["fuzz"]["env"])
        except G.GrammarError:
            accepted, value = False, None
        assert accepted == case["accepted"], case
        if accepted:
            assert _close(value, _num(case["expected"]), 1e-12), case


def test_random_text_is_refused_cleanly_or_parsed():
    """Any printable text either parses or raises GrammarError: no other
    exception, no evaluation of what it says (G21, fuzzed)."""

    rng = random.Random(7)
    alphabet = [chr(code) for code in range(32, 127)] + ["é", "٣", " ", "\n", "\t"]
    accepted = 0
    for _ in range(4000):
        text = "".join(rng.choice(alphabet) for _ in range(rng.randint(0, 24)))
        try:
            node = G.parse(text)
        except G.GrammarError:
            continue
        accepted += 1
        G.evaluate(node, {})  # never raises: unbound names are NaN
    assert accepted < 4000


def test_g21_no_code_execution_in_the_figures_package():
    """The figure package never evaluates text as code: no eval, exec,
    compile or __import__ call anywhere in it (a lint over its source)."""

    banned = {"eval", "exec", "compile", "__import__"}
    for path in FIGURES_PACKAGE.glob("*.py"):
        tree = ast.parse(path.read_text(encoding="utf-8"))
        for node in ast.walk(tree):
            if isinstance(node, ast.Call) and isinstance(node.func, ast.Name):
                assert node.func.id not in banned, f"{path.name} calls {node.func.id}"


def test_g45_two_sided_exponential_p_whatever_lambda():
    """P(X ≤ 0) = p at every λ, from the readout (Python's integration)."""

    compiled = S.parse_spec(FC.flagship_spec())
    for p in (0.05, 0.3, 0.6, 0.95):
        for lam in (0.5, 1.0, 2.0, 4.0):
            data = S.evaluate_figure(compiled, {"p": p, "lam": lam})
            readout = data["panels"][1]["value"]
            shade_left, shade_right = data["panels"][0]["shades"]
            exact = p * (1 - math.exp(-lam * 40))
            assert abs(readout - exact) <= 1e-6
            assert shade_left["value"] == readout
            assert abs(shade_left["value"] + shade_right["value"] - (1 - math.exp(-lam * 40))) <= 1e-6
    assert S.evaluate_figure(compiled, {"p": 0.3})["panels"][1]["value"] == pytest.approx(0.30, abs=1e-6)
    outcome = S.prediction_outcome(compiled, 0)
    assert outcome["answer"] == "same" and outcome["change"] == {"lam": 2.0}


def test_simpson_reads_a_jump_from_the_correct_side():
    left = G.parse("integral(piecewise((t < 0, 1), 3), t, -1, 0)")
    right = G.parse("integral(piecewise((t < 0, 1), 3), t, 0, 1)")
    assert G.evaluate(left, {}) == pytest.approx(1.0, abs=1e-12)
    assert G.evaluate(right, {}) == pytest.approx(3.0, abs=1e-12)


def test_integral_budget_and_sum_cap():
    noisy = G.parse("integral(piecewise((sin(1000000*t) < 0, 1), -1), t, 0, 1000)")
    assert math.isnan(G.evaluate(noisy, {})) or math.isfinite(G.evaluate(noisy, {}))
    assert math.isnan(G.evaluate(G.parse("sum(k, k, 0, 20000)"), {}))
    assert G.evaluate(G.parse("sum(k, k, 0, 10000)"), {}) == 50005000.0
