-- Adaptive hints H1: approach maps (spec_adaptive_hints_v1 §4.3, §4.3.1, §9,
-- §10 H1, G-H9; docs/reviews/adaptive-hints-H1.md).
--
-- One row per approach map VERSION of one practice item: a small subgoal
-- graph (nodes, edges, routes with their origin) built by one model call
-- (route approach_map) from the item's reference solution, rubric, authored
-- hints, trace contract, PF skeleton, the learner's own textbook worked
-- examples and the learner's own correct solutions. A revised item, changed
-- seeds or a learner-route merge is a NEW row (version + 1, supersedes_id),
-- never an update: rows are immutable.
--
-- WORKFLOW: paid output, never rebuilt and never regenerated by replay or
-- rebuild (standing constraint H6); no DERIVED table, so no replayer. Never
-- evidence: no scoring, scheduling, projection, serving, grading or replay
-- path reads it, and the grader never sees it (standing constraint H2).
-- help_assists.map_id (migration 210) names a row here as a soft reference,
-- validated in code (no foreign key; H0 friction note 1). Kill switch:
-- hints.maps.enabled (off: nothing is built and nothing reads this table).
CREATE TABLE approach_maps (
  id TEXT PRIMARY KEY,
  practice_item_id TEXT NOT NULL,
  -- The item revision the map was built for (vault/hashes.py).
  practice_item_hash TEXT NOT NULL,
  family_id TEXT,
  -- 1, 2, ... per item, across revisions.
  version INTEGER NOT NULL CHECK (version >= 1),
  -- ApproachMapV1, as validated (code-marked leak nodes included).
  map_json TEXT NOT NULL,
  -- Which trace contract, skeletons, source spans, attempts, authored hints
  -- and family template the map was built from.
  seeds_json TEXT NOT NULL,
  -- The revision keys: every seed (seeds_hash), and the item-side seeds that
  -- practice_item_hash does not cover (structure_hash: the trace contract,
  -- the PF skeletons and the authored hints). A serve builds a map when no
  -- row matches the item's current practice_item_hash and structure_hash.
  seeds_hash TEXT NOT NULL,
  structure_hash TEXT NOT NULL,
  validation_json TEXT NOT NULL,
  -- 1 when the goal agrees with the expected answer by exact key; 0 when no
  -- exact key exists or the agreement cannot be decided (the builder's
  -- declaration, stored as unverified).
  verified_goal INTEGER NOT NULL CHECK (verified_goal IN (0, 1)),
  -- What built this version: a serve (background), an inline build (H2's
  -- hint path), the owner's CLI backfill, or a learner-route merge.
  trigger TEXT NOT NULL CHECK (trigger IN ('serve', 'inline', 'cli', 'merge')),
  model TEXT,
  prompt_version TEXT NOT NULL,
  input_hash TEXT NOT NULL,
  created_at TEXT NOT NULL,
  supersedes_id TEXT REFERENCES approach_maps(id),
  CHECK (supersedes_id IS NULL OR supersedes_id != id),
  UNIQUE (practice_item_id, version),
  UNIQUE (practice_item_id, practice_item_hash, seeds_hash)
);
CREATE INDEX idx_approach_maps_item ON approach_maps(practice_item_id, version);
CREATE INDEX idx_approach_maps_family ON approach_maps(family_id, created_at);

CREATE TRIGGER approach_maps_no_update
BEFORE UPDATE ON approach_maps
BEGIN
  SELECT RAISE(ABORT, 'approach_maps rows are immutable: a new version is a new row');
END;

CREATE TRIGGER approach_maps_no_delete
BEFORE DELETE ON approach_maps
BEGIN
  SELECT RAISE(ABORT, 'approach_maps rows are paid output and are never deleted');
END;
